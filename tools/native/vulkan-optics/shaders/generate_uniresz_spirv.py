"""Build the integer-exact 1024x576 to 640x360 UniResz compute shader."""
from pathlib import Path

from generate_scene3d_spirv import (
    SpirvBuilder, OP_UDIV, OP_SHIFT_LEFT_LOGICAL, OP_BITWISE_OR, format_array,
)


def shader():
    b = SpirvBuilder(32, 4, 1)
    src, src_ptr = b.ssbo_array(b.t_u32, 4, 0)
    dst, dst_ptr = b.ssbo_array(b.t_u32, 4, 1)
    params = b.uniform_struct([b.t_u32] * 4, 2)
    pair, row = b.gid(0), b.gid(1)
    stride = b.load_ubo(params, 0, False)
    yyuv = b.une(b.load_ubo(params, 1, False), b.u32(0))

    def div(value, n):
        return b.op(OP_UDIV, b.t_u32, value, b.u32(n))

    def coords(i, src_last, dst_last):
        n = b.umul(i, b.u32(src_last))
        lo = div(n, dst_last)
        frac = b.usub(n, b.umul(lo, b.u32(dst_last)))
        return lo, b.umin(b.uadd(lo, b.u32(1)), b.u32(src_last)), frac

    def source(x, y):
        i = b.uadd(b.umul(y, stride), b.ushr(x, b.u32(1)))
        w = b.load_ssbo(src, src_ptr, b.t_u32, i)
        black = b.lor(b.ueq(w, b.u32(0)), b.lor(b.ueq(w, b.u32(0x80800000)), b.ueq(w, b.u32(0x00008080))))
        w = b.sel_u(black, b.u32(0x00800080), w)
        y_shift = b.sel_u(b.ueq(b.uand(x, b.u32(1)), b.u32(0)), b.u32(8), b.u32(24))
        return [b.uand(b.ushr(w, y_shift), b.u32(255)), b.uand(w, b.u32(255)), b.uand(b.ushr(w, b.u32(16)), b.u32(255))]

    y0, y1, wy = coords(row, 575, 359)
    def resample(x):
        x0, x1, wx = coords(x, 1023, 639)
        a, c, d, e = source(x0, y0), source(x1, y0), source(x0, y1), source(x1, y1)
        complement = b.usub(b.u32(639), wx)
        def horizontal(left, right):
            return b.uadd(b.umul(left, complement), b.umul(right, wx))
        def channel(k):
            top, bottom = horizontal(a[k], c[k]), horizontal(d[k], e[k])
            n = b.uadd(b.umul(top, b.usub(b.u32(359), wy)), b.umul(bottom, wy))
            # Both denominators are odd, so no rational sample is exactly halfway.
            return div(b.uadd(n, b.u32((639 * 359) // 2)), 639 * 359)
        return [channel(k) for k in range(3)]
    x = b.umul(pair, b.u32(2))
    l0, u0, v0 = resample(x)
    l1, u1, v1 = resample(b.uadd(x, b.u32(1)))
    u, v = b.ushr(b.uadd(u0, u1), b.u32(1)), b.ushr(b.uadd(v0, v1), b.u32(1))
    values = [b.sel_u(yyuv, a, c) for a, c in zip([l0, l1, u, v], [u, l0, v, l1])]
    word = values[0]
    for i in range(1, 4):
        shifted = b.op(OP_SHIFT_LEFT_LOGICAL, b.t_u32, values[i], b.u32(8*i))
        word = b.op(OP_BITWISE_OR, b.t_u32, word, shifted)
    b.store_ssbo(dst, dst_ptr, b.uadd(b.umul(row, b.u32(320)), pair), word)
    return b.finish()


if __name__ == "__main__":
    header = Path(__file__).resolve().parent.parent / "fuji_vulkan_uniresz_spirv.h"
    with header.open("w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by shaders/generate_uniresz_spirv.py.\n#pragma once\n")
        out.write(format_array("kSpvUniResz", shader()) + "\n")
