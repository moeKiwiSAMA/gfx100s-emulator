/**
 * Standard photographic 1/3-stop aperture progression used to enumerate exact per-lens aperture stops.
 */
object ApertureScale {
    val THIRD_STOPS: List<Double> = listOf(
        1.0, 1.1, 1.2, 1.4, 1.6, 1.8, 2.0, 2.2, 2.5, 2.8, 3.2, 3.5, 4.0,
        4.5, 5.0, 5.6, 6.4, 7.1, 8.0, 9.0, 10.0, 11.0, 13.0, 14.0, 16.0,
        18.0, 20.0, 22.0, 25.0, 29.0, 32.0, 36.0, 40.0, 45.0, 51.0, 57.0, 64.0,
    )

    fun stopsBetween(minAperture: Double, maxAperture: Double): List<Double> {
        val lo = minOf(minAperture, maxAperture)
        val hi = maxOf(minAperture, maxAperture)
        val out = ArrayList<Double>()
        if (THIRD_STOPS.none { kotlin.math.abs(it - lo) < 0.02 }) {
            out.add(lo)
        }
        for (stop in THIRD_STOPS) {
            if (stop >= lo - 0.02 && stop <= hi + 0.02) {
                out.add(stop)
            }
        }
        if (out.isEmpty() || kotlin.math.abs(out.last() - hi) >= 0.02) {
            out.add(hi)
        }
        return out
    }
}

