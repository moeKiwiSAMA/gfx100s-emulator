    const val LM_FAST = "LM_FAST"
    const val LM = "LM"
    const val STM = "STM"
    const val USM = "USM"
    const val DC_CORELESS = "DC_CORELESS"
    const val MANUAL = "MANUAL"

    val ALL: List<String> = listOf(LM_FAST, LM, STM, USM, DC_CORELESS, MANUAL)
}

/**
 * Built-in optical lens & adapter template definition for M9 optical pipeline simulation.
 *
 * **Evidence classification (`HYPOTHESIS` / `SIM`)**: Optical aberration, contrast drop, flare,
 * bokeh highlight shape, vignetting, image circle, MFD, and focus-motor sweep parameters are
 * analytical physical simulation profiles derived from real-world FUJIFILM GF / Canon EF /
 * Super-Takumar / Carl Zeiss Planar specifications and optical bench characteristics, not factory
 * lens EEPROM calibration tables.
 */
data class LensTemplate(
    val id: String,
    val displayName: String,
    val mountType: String,
    val modelName: String,
    val defaultFocalLengthMm: Double,
    val referenceFocalLengthMm: Double,
    val minFocalLengthMm: Double,
    val maxFocalLengthMm: Double,
    val defaultAperture: Double,
    val minAperture: Double,
    val maxAperture: Double,
    val minFocusDistanceM: Double,
    val teleMinFocusDistanceM: Double = minFocusDistanceM,
    val defaultFocusDistanceM: Double,
    val transmission: Double,
    val focusBreathing: Double,
    val distortionK1: Double,
    val distortionK2: Double,
    val caRedScale: Double,
    val caBlueScale: Double,
    val longitudinalCaDefocusMm: Double = 0.0,
    val wideOpenContrastDrop: Double = 0.0,
    val vignettingCos4: Double,
    val vignettingMechanical: Double,
    val imageCircleMm: Double,
    val electronicContacts: Boolean,
    val oisEnabled: Boolean,
    val defaultFocusMode: String,
    val focusMotorType: String = FocusMotorTypes.LM,
    val focusSweepSeconds: Double = 0.35,
    val flareStrength: Double = 0.0,
    val flareTintR: Double = 1.0,
    val flareTintG: Double = 0.95,
    val flareTintB: Double = 0.88,
    val apertureBladeCount: Int = 9,
    val apertureBladeRoundness: Double = 0.85,
    val bokehCatsEye: Double = 0.0,
    val bokehOnionRing: Double = 0.0,
    val bokehRimHighlight: Double = 0.0,
    val opticalCharacterSummary: String = "",
    val opticalCharacterSummaryZh: String = "",
) {
    val apertureStops: List<Double>
        get() = ApertureScale.stopsBetween(minAperture, maxAperture)

    /**
     * Effective minimum focus distance at [focalLengthMm], interpolating linearly between
     * wide-end [minFocusDistanceM] and tele-end [teleMinFocusDistanceM] on zoom lenses.
     */
    fun effectiveMinFocusDistanceM(focalLengthMm: Double): Double {
        if (maxFocalLengthMm - minFocalLengthMm <= 1e-3 || teleMinFocusDistanceM == minFocusDistanceM) {
            return minFocusDistanceM
        }
        val t = ((focalLengthMm - minFocalLengthMm) / (maxFocalLengthMm - minFocalLengthMm)).coerceIn(0.0, 1.0)
        return minFocusDistanceM + (teleMinFocusDistanceM - minFocusDistanceM) * t
    }

    /**
     * Converts this template into a scalar setting map suitable for `LensFactory` defaults.
     * Note that `opticsEnabled` and `focusMotorInstant` are intentionally omitted so caller/profile
     * decides whether to enable live optics or instant vs physical focus motor travel.
     */
