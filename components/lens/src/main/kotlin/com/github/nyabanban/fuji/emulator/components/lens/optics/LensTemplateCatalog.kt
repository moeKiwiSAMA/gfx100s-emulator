        "wideOpenContrastDrop" to wideOpenContrastDrop,
        "vignettingCos4" to vignettingCos4,
        "vignettingMechanical" to vignettingMechanical,
        "imageCircleMm" to imageCircleMm,
        "electronicContacts" to electronicContacts,
        "oisEnabled" to oisEnabled,
        "focusMode" to defaultFocusMode,
        "focusMotorType" to focusMotorType,
        "focusSweepSeconds" to focusSweepSeconds,
        "flareStrength" to flareStrength,
        "flareTintR" to flareTintR,
        "flareTintG" to flareTintG,
        "flareTintB" to flareTintB,
        "apertureBladeCount" to apertureBladeCount.toLong(),
        "apertureBladeRoundness" to apertureBladeRoundness,
        "bokehCatsEye" to bokehCatsEye,
        "bokehOnionRing" to bokehOnionRing,
        "bokehRimHighlight" to bokehRimHighlight,
    )

    fun toSummaryMap(): Map<String, Any> = linkedMapOf(
        "id" to id,
        "displayName" to displayName,
        "mountType" to mountType,
        "model" to modelName,
        "defaultFocalLengthMm" to defaultFocalLengthMm,
        "minFocalLengthMm" to minFocalLengthMm,
        "maxFocalLengthMm" to maxFocalLengthMm,
        "defaultAperture" to defaultAperture,
        "minAperture" to minAperture,
        "maxAperture" to maxAperture,
        "apertureStops" to apertureStops,
        "minFocusDistanceM" to minFocusDistanceM,
        "teleMinFocusDistanceM" to teleMinFocusDistanceM,
        "imageCircleMm" to imageCircleMm,
        "electronicContacts" to electronicContacts,
        "oisEnabled" to oisEnabled,
        "defaultFocusMode" to defaultFocusMode,
        "focusMotorType" to focusMotorType,
        "focusSweepSeconds" to focusSweepSeconds,
        "caRedScale" to caRedScale,
        "caBlueScale" to caBlueScale,
        "longitudinalCaDefocusMm" to longitudinalCaDefocusMm,
        "wideOpenContrastDrop" to wideOpenContrastDrop,
        "flareStrength" to flareStrength,
        "flareTintR" to flareTintR,
        "flareTintG" to flareTintG,
        "flareTintB" to flareTintB,
        "apertureBladeCount" to apertureBladeCount,
        "apertureBladeRoundness" to apertureBladeRoundness,
        "bokehCatsEye" to bokehCatsEye,
